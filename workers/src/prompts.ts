// ── 工具函數：把對話紀錄格式化給 result prompt 用 ─────────────────
export function buildConversationText(topic: string, messages: Array<{ role: string; content: string }>): string {
  const conversation = messages
    .map(m => `${m.role === 'assistant' ? '小兔兔' : '小主人'}：${m.content}`)
    .join('\n')
  return `以下是引導國小學生寫作的對話紀錄，作文題目是「${topic}」。\n\n${conversation}`
}
